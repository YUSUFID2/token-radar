/**
 * The category multiplier table, in ONE place: [substring to match (lowercase), multiplier].
 * Checked in order, so "yield aggregator" (0.85) is tried before "yield" (0.90). A category that
 * matches nothing scores 1.00, the same as CDP's stated 1.00.
 */
export const CATEGORY_MULTIPLIERS: ReadonlyArray<readonly [string, number]> = [
  ['risk curator', 1.25],
  ['onchain capital allocator', 1.2],
  ['derivative', 1.15],
  ['dexs', 1.1],
  ['lending', 1.05],
  ['cdp', 1.0],
  ['rwa', 0.95],
  ['yield aggregator', 0.85],
  ['yield', 0.9],
  ['payment', 0.8],
];

/** Categories whose launches the likelihood bonus rewards, matched case-insensitively. */
const LIKELIHOOD_CATEGORIES = new Set(['risk curators', 'onchain capital allocator', 'derivatives', 'dexs', 'lending']);

/** Categories the full watchlist rule refuses on every rankable row, matched case-insensitively.
 * "Cross Chain Bridge" is a bridge product too, so it is refused with "Bridge". */
const EXCLUDED_CATEGORIES = new Set(['cex', 'bridge', 'canonical bridge', 'cross chain bridge', 'liquid staking', 'liquid restaking', 'restaked btc']);

