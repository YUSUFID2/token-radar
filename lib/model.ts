// Token radar, model "radar-2": one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// strongest pre-token protocols below the watchlist floor: the early rows the radar exists to find.
// A protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id, no
// symbol); the snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board.
//
// Rankable means pre-token AND the full watchlist rule: the category is not an exchange, a bridge, a
// liquid-staking / liquid-restaking / restaked-BTC product, the name carries no whole word wrapped,
// staked or staking, it does not start with an exchange's name, and it is not a versioned pool. A
// wrapped or staked product of a token that already trades is not a protocol still waiting on a
// launch of its own, so it never ranks here.
//
// Implied value follows only from the snapshot's own figures (no protocol name is ever special-cased):
//
//   base          = tvl_usd x 0.25
//   growthPct     = clamp(change_7d, -60, 120) per cent
//   growthMult    = 1 + (growthPct / 100) x 0.5
//   maturityMult  = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   categoryMult  = the table below (fee-generating vault / derivative businesses command a higher
//                   launch FDV per TVL than pass-through yield)
//   chainMult     = 1 + 0.02 x min(chains - 1, 5)            (at most 1.10)
//   likelihood    = 0.70, +0.10 when age_days >= 365, +0.10 when growthPct > 0,
//                   +0.10 when the category is a launch-heavy one; clamped to [0.40, 1.00]
//   implied       = max(1, round(base x growthMult x maturityMult x categoryMult x chainMult
//                   x likelihood))
//
// Every row keeps its model breakdown, so the dashboard can show exactly how its rank was earned.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

